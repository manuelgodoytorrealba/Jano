import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputFile = path.resolve(__dirname, '../src/app/core/i18n/i18n-release.ts');

const release = process.env.JANO_RELEASE?.trim() || process.env.GIT_COMMIT?.trim();

if (!release) {
  console.log('i18n release version: development (source file unchanged)');
  process.exit(0);
}

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(
  outputFile,
  `// Generated by frontend/scripts/generate-i18n-release.mjs during release builds.\nexport const I18N_RELEASE = '${release.replaceAll("'", "\\'")}';\n`,
);

console.log(`i18n release version: ${release}`);
