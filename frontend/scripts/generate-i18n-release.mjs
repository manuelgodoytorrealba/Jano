import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputFile = path.resolve(__dirname, '../src/app/core/i18n/i18n-release.ts');

function gitRevision() {
  try {
    return execFileSync('git', ['rev-parse', '--short=12', 'HEAD'], {
      cwd: path.resolve(__dirname, '..'),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return null;
  }
}

const release =
  process.env.JANO_RELEASE?.trim() ||
  process.env.GIT_COMMIT?.trim() ||
  gitRevision() ||
  new Date()
    .toISOString()
    .replace(/[^0-9]/g, '')
    .slice(0, 14);

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(
  outputFile,
  `// Generated by frontend/scripts/generate-i18n-release.mjs during build.\nexport const I18N_RELEASE = ${JSON.stringify(release)};\n`,
);

console.log(`i18n release version: ${release}`);
